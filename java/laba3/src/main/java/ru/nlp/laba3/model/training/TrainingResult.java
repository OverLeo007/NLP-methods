package ru.nlp.laba3.model.training;

/** Обученное состояние и фактические размеры модели, общие для всех алгоритмов. */
public record TrainingResult<M>(
        /** Обученное состояние конкретного алгоритма. */
        M model,
        /** Число терминов в обученной модели. */
        int vocabularySize,
        /** Фактическое число координат вектора. */
        int dimensions,
        /** Внутренний замер тренера после захвата нативного монитора, в секундах. */
        double seconds
) {}
